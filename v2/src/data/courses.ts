export function getCourseById(id: string) {
  return COURSES.find(c => c.id === id)
}

export function getCoursesByLevelSemester(level: string, semester: string, faculty?: string, department?: string) {
  return COURSES.filter(c => {
    if (c.level !== level) return false
    if (c.semester !== semester) return false
    if (faculty && c.faculty !== 'all' && c.faculty !== faculty) return false
    if (department && c.department !== 'all' && c.department !== department) return false
    return true
  })
}
